// Generate stub event entries for every Release 01 PDF that's in
// Denis's Gemini corpus but isn't yet curated in src/data/events.js.
//
// Writes src/data/events-auto.js — a separate file the main events.js
// imports and concatenates. Keeps the 52 hand-curated entries untouched
// while expanding coverage to the full 120-PDF release.
//
// Stubs are deliberately minimal: id, title, date, agency, url, coords,
// type. A human curator can later promote a stub into a fully-curated
// entry in events.js and remove its auto-counterpart.

import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const MANIFEST = path.join(ROOT, "data-raw", "upstream-gemini", "metadata", "pdf_manifest.tsv");
const UNMATCHED = path.join(ROOT, "data-raw", ".upstream-gemini-unmatched.json");
const OUT = path.join(ROOT, "src", "data", "events-auto.js");

// Approximate location anchors keyed by agency. Picked so the geospatial
// dial doesn't collapse all stubs to a single coordinate (which would
// hide visual distribution); a human curator can refine these.
const AGENCY_LOC = {
  "FBI":                    { loc: "Washington, DC",      region: "North America", coords: [38.895, -77.014], tag: "FBI" },
  "Department of War":      { loc: "Arlington, VA",       region: "North America", coords: [38.87,  -77.055], tag: "DoW" },
  "Department of State":    { loc: "Washington, DC",      region: "North America", coords: [38.894, -77.048], tag: "DoS" },
  "NASA":                   { loc: "Houston, TX",         region: "North America", coords: [29.555, -95.091], tag: "NASA" },
};
const DEFAULT_LOC = { loc: "United States", region: "North America", coords: [39.0, -98.0], tag: "uncategorized" };

function slugify(s) {
  return s.toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-")
    .slice(0, 64);
}

function titleize(s) {
  return s
    .replace(/[_-]+/g, " ")
    .replace(/\.pdf$/i, "")
    .replace(/\b\w/g, c => c.toUpperCase())
    .trim();
}

function eraOf(year) {
  if (!year) return null;
  const decade = Math.floor(year / 10) * 10;
  return `${decade % 100}s`;
}

function parseManifest(tsv) {
  const out = new Map();   // url (lowercase) → row
  for (const line of tsv.split(/\r?\n/)) {
    if (!line.trim()) continue;
    const [filename, url, slug, agency, releaseDate] = line.split("\t");
    if (!url) continue;
    out.set(url.toLowerCase(), { filename, url, slug, agency, releaseDate });
  }
  return out;
}

const tsv = await readFile(MANIFEST, "utf8");
const manifestByUrl = parseManifest(tsv);

if (!existsSync(UNMATCHED)) {
  console.error(`[auto-catalogue] no ${UNMATCHED} — run import-gemini-corpus.mjs first`);
  process.exit(1);
}
const unmatched = JSON.parse(await readFile(UNMATCHED, "utf8"));

// Avoid id collisions with curated events.js.
const { EVENTS } = await import(`../src/data/events.js?cb=${Date.now()}`);
const curatedIds = new Set(EVENTS.map(e => e.id));

const stubs = [];
const idCounts = new Map();
for (const u of unmatched) {
  const row = manifestByUrl.get((u.source_url || "").toLowerCase());
  const slugSrc = row?.slug || u.folder.replace(/^\d+-/, "");
  let baseId = slugify(slugSrc);
  // Disambiguate if collision (FBI section files often share prefixes).
  const n = (idCounts.get(baseId) || 0) + 1;
  idCounts.set(baseId, n);
  let id = baseId;
  if (curatedIds.has(id)) id = `${baseId}-auto`;
  if (n > 1) id = `${id}-${n}`;

  const agency = row?.agency || "Unknown";
  const loc = AGENCY_LOC[agency] || DEFAULT_LOC;

  // Year: 5/8/26 in the manifest is the release date, not the document
  // date. We leave date null until a curator fills it in from the
  // transcript itself.
  stubs.push({
    id,
    title: titleize(slugSrc),
    date: null,
    sort: 99999999,
    era: null,
    loc: loc.loc,
    region: loc.region,
    coords: loc.coords,
    agency,
    type: "Document",
    flag: "low",
    auto: true,
    summary: `Auto-catalogued from Gemini transcription. ${u.page_count}-page document. Awaiting human curation of date, location, and summary.`,
    url: row?.filename?.toLowerCase() || u.source_url?.split("/").pop()?.toLowerCase() || null,
    tags: ["auto-imported", "gemini-sourced", loc.tag],
    page_count: u.page_count,
  });
}

// Format the output file. We hand-format to keep diffs readable and to
// mirror the curated events.js style (one object per line).
const lines = [
  "// =================================================================",
  "// PURSUE Release 01 — AUTO-CATALOGUED entries",
  "//",
  "// Generated by scripts/auto-catalogue-from-gemini.mjs from",
  "// DenisSergeevitch/UFO-USA's pdf_manifest.tsv. Every entry here is a",
  "// stub awaiting human curation — promote into events.js once you've",
  "// read the document and filled in date/location/summary properly.",
  "// =================================================================",
  "export const EVENTS_AUTO = [",
];
for (const s of stubs) {
  const obj = {
    id: s.id, title: s.title, date: s.date, sort: s.sort, era: s.era,
    loc: s.loc, region: s.region, coords: s.coords, agency: s.agency,
    type: s.type, flag: s.flag, auto: s.auto, summary: s.summary,
    url: s.url, tags: s.tags, page_count: s.page_count,
  };
  // JSON5-ish: keys unquoted not worth the parser; standard JSON works
  // fine here because events.js entries are valid JSON-compatible objects.
  lines.push(`  ${JSON.stringify(obj)},`);
}
lines.push("];");
lines.push("");

await writeFile(OUT, lines.join("\n"), "utf8");
console.log(`[auto-catalogue] wrote ${OUT} — ${stubs.length} stub events`);

// By agency for sanity
const byAgency = {};
for (const s of stubs) byAgency[s.agency] = (byAgency[s.agency] || 0) + 1;
console.log(`[auto-catalogue] by agency:`);
for (const [a, n] of Object.entries(byAgency).sort((a,b) => b[1]-a[1])) {
  console.log(`   ${a.padEnd(22)} ${n}`);
}
