// Auto-generate CONTRIBUTORS.md from the corpus.
//
// Three credit sources, deduped by handle:
//   1. data-raw/.contributions-manifest.json  — every page imported via PR
//   2. data-raw/.visuals/<eid>/p<NNN>.json    — pages where classifier="human:<handle>"
//   3. data-raw/corpus.sqlite contributions   — provenance log (same as 1, but DB-side)
//
// Output: CONTRIBUTORS.md with one section per handle, sorted by total
// pages contributed descending. Updates on every build so nobody has
// to remember to regenerate it. The doc this replaces (manually-edited
// CONTRIBUTORS.md) never existed — multiple docs referenced it, none
// of them was true. This script makes them true.

import { readFile, readdir, writeFile, stat } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const MANIFEST = path.join(ROOT, "data-raw", ".contributions-manifest.json");
const VISUALS_DIR = path.join(ROOT, "data-raw", ".visuals");
const OUT = path.join(ROOT, "CONTRIBUTORS.md");

const contributors = new Map();  // handle -> { transcriptions: {<source>: n}, media: n, firstAt, lastAt, events: Set }

function bump(handle, field, count = 1, eid = null, at = null) {
  if (!handle) return;
  if (!contributors.has(handle)) {
    contributors.set(handle, { transcriptions: {}, media: 0, firstAt: null, lastAt: null, events: new Set() });
  }
  const c = contributors.get(handle);
  if (field === "media") {
    c.media += count;
  } else {
    c.transcriptions[field] = (c.transcriptions[field] || 0) + count;
  }
  if (eid) c.events.add(eid);
  if (at) {
    if (!c.firstAt || at < c.firstAt) c.firstAt = at;
    if (!c.lastAt || at > c.lastAt) c.lastAt = at;
  }
}

// 1. Contribution manifest (transcription PRs imported into vision-cache)
if (existsSync(MANIFEST)) {
  try {
    const m = JSON.parse(await readFile(MANIFEST, "utf8"));
    for (const [key, val] of Object.entries(m)) {
      const eid = key.split("/")[0];
      bump(val.handle, val.source || "gpt-vision", 1, eid, val.importedAt);
    }
  } catch {}
}

// 2. Visuals sidecars (media-context submissions, classifier="human:<handle>")
async function listDirs(p) {
  try { return (await readdir(p, { withFileTypes: true })).filter(d => d.isDirectory()).map(d => d.name); }
  catch { return []; }
}
for (const eid of await listDirs(VISUALS_DIR)) {
  const dir = path.join(VISUALS_DIR, eid);
  for (const f of await readdir(dir)) {
    if (!/^p\d+\.json$/.test(f)) continue;
    try {
      const sc = JSON.parse(await readFile(path.join(dir, f), "utf8"));
      const cl = sc.classifier || "";
      if (cl.startsWith("human:")) {
        const handle = cl.slice("human:".length);
        bump(handle, "media", 1, eid, sc.classifiedAt);
      }
    } catch {}
  }
}

const sorted = [...contributors.entries()]
  .map(([handle, c]) => ({
    handle,
    totalPages: Object.values(c.transcriptions).reduce((s, n) => s + n, 0) + c.media,
    ...c,
    events: [...c.events].sort(),
  }))
  .sort((a, b) => b.totalPages - a.totalPages);

const lines = [];
lines.push("# Contributors");
lines.push("");
lines.push("> Auto-generated by `scripts/build-contributors.mjs` on every build. **Do not edit by hand** — your change will be overwritten on the next deploy. To get on this list, contribute a transcription or media submission per [HOW-CAN-I-HELP.md](./HOW-CAN-I-HELP.md).");
lines.push("");

if (!sorted.length) {
  lines.push("_No contributions yet. Be the first._");
} else {
  lines.push(`**${sorted.length} contributor${sorted.length === 1 ? "" : "s"}** · **${sorted.reduce((s, c) => s + c.totalPages, 0)}** pages contributed across **${new Set(sorted.flatMap(c => c.events)).size}** event${new Set(sorted.flatMap(c => c.events)).size === 1 ? "" : "s"}.`);
  lines.push("");
  lines.push("| Handle | Total | Source breakdown | First contribution | Last contribution |");
  lines.push("|---|---:|---|---|---|");
  for (const c of sorted) {
    const breakdown = [
      ...Object.entries(c.transcriptions).map(([s, n]) => `${s} ×${n}`),
      c.media ? `media ×${c.media}` : null,
    ].filter(Boolean).join(" · ");
    const first = c.firstAt ? c.firstAt.slice(0, 10) : "—";
    const last  = c.lastAt  ? c.lastAt.slice(0, 10)  : "—";
    lines.push(`| **@${c.handle}** | ${c.totalPages} | ${breakdown} | ${first} | ${last} |`);
  }
  lines.push("");
  lines.push("## Per-contributor detail");
  lines.push("");
  for (const c of sorted) {
    lines.push(`### @${c.handle}`);
    lines.push("");
    lines.push(`- **${c.totalPages} pages** across ${c.events.length} event${c.events.length === 1 ? "" : "s"}: ${c.events.map(e => `\`${e}\``).join(", ")}`);
    for (const [src, n] of Object.entries(c.transcriptions)) {
      lines.push(`- **${src}**: ${n} page${n === 1 ? "" : "s"}`);
    }
    if (c.media) lines.push(`- **media (image + context)**: ${c.media} page${c.media === 1 ? "" : "s"}`);
    lines.push("");
  }
}

lines.push("---");
lines.push("");
lines.push(`_Generated ${new Date().toISOString()} — regenerated on every build._`);

await writeFile(OUT, lines.join("\n") + "\n", "utf8");
console.log(`[contributors] wrote ${OUT} — ${sorted.length} contributor(s)`);
